-- -------------------- 2. 为 id>=5 的用户补充点赞数据 --------------------
-- 每个用户对若干帖子点赞，使用 INSERT IGNORE 避免主键冲突
INSERT IGNORE INTO user_likes(user_id, post_id)
SELECT u.id, p.id
FROM users u
JOIN posts p ON p.id IN (22, 25, 28, 29, 30, 32, 35, 49, 55, 56, 57, 59,
                         (SELECT id FROM posts WHERE title='期末高数复习笔记分享'),
                         (SELECT id FROM posts WHERE title='求四六级备考搭子'),
                         (SELECT id FROM posts WHERE title='二食堂麻辣香锅测评'),
                         (SELECT id FROM posts WHERE title='三舍橘猫求领养'),
                         (SELECT id FROM posts WHERE title='Java多线程问题求助'))
WHERE u.id >= 5
  -- 用 user_id 取模控制每个用户点赞的帖子子集，避免所有人点赞相同帖子
  AND (u.id + p.id) % 3 IN (0, 1);

-- 更新帖子点赞计数
UPDATE posts p SET likes = (
    SELECT COUNT(*) FROM user_likes WHERE post_id = p.id
);

